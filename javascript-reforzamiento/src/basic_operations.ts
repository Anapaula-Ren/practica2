function sumar (value1:number, value2:number)
{
return value1 + value2
}

function multiplicar (value1:number, value2:number)
{
return value1 * value2
}

function restar (value1:number, value2:number)
{
return value1 - value2
}

function divdir (value1:number, value2:number)
{
return value1 / value2
}

export{sumar, restar, multiplicar, divdir}